def get_soft_caps_for(game_version, char_class):
    """Characteristic soft caps for a class, honouring the game version.

    Retro (1.29) has class-specific costs; Touch keeps its own 2.x-era uniform
    table (Wisdom distributable, elements to a 5:1 tier); every other version
    shares the modern uniform table. Falls back to the default table for any
    class not listed (e.g. a modern-only class should never reach the retro table)."""
    if game_version == 'retro':
        return SOFT_CAPS_RETRO.get(char_class, DEFAULT_SOFT_CAPS)
    if game_version == 'touch':
        return DEFAULT_SOFT_CAPS_TOUCH
    return SOFT_CAPS.get(char_class, DEFAULT_SOFT_CAPS)


def scrolls_push_cost_curve(game_version):
    """Whether scrolled points consume the cheap characteristic cost tiers.

    Retro (1.29) and Touch (2.x fork frozen before update 2.48) use the old
    rule: a character scrolled to 100 pays its first invested point at the
    2:1 tier. Since Dofus 2.48 (October 2018) scrolled points are tracked
    separately and never push the cost curve, so dofus2 (2.73), dofus3 and
    beta all pay 1:1 for the first 100 invested points regardless of scrolls.
    Source: tofus.fr/fiches/parchemin.php ("Depuis octobre 2018, les points
    additionnels sont comptes separement des points naturels")."""
    return game_version in ('retro', 'touch')


def tier_widths_after_scroll(caps_for_stat, scrolled):
    """Per-tier room left for characteristic points once scrolls are accounted for.

    Scrolls are free stat but still push you up the cost curve: an Iop scrolled
    to 100 Intelligence already fills the cheap early tiers, so the next point
    costs 5:1, not 1:1. caps_for_stat is the 6-slot cumulative-threshold list
    (None = unlimited from that tier on); we subtract the scrolled base from the
    tiers it covers and return the remaining width per tier (None = unlimited)."""
    scrolled = scrolled or 0
    widths = []
    for i in range(6):
        lo = 0 if i == 0 else caps_for_stat[i - 1]
        hi = caps_for_stat[i]
        if hi is None:
            widths.append(None)
        elif lo is None:
            widths.append(0)
        else:
            consumed = max(0, min(scrolled, hi) - lo)
            widths.append(max(0, (hi - lo) - consumed))
    return widths


def max_scroll_for_version(game_version):
    """Highest a characteristic can be scrolled, per version. Touch's Dedale
    (update 1.73, live June 2026) added scrolls that push the six main stats to
    150; Retro allows 101; every other version caps at 100."""
    if game_version == 'touch':
        return 150
    if game_version == 'retro':
        return 101
    return 100


ATTRIBUTE_TO_ELEMENT = {
    'int': 'fire',
    'cha': 'water',
    'agi': 'air',
    'str': 'earth'
}

def get_best_element(char_stats):
    best_element = 'str'
    best_element_val = char_stats['str']
    for element in ['int', 'cha', 'agi']:
        if char_stats[element] > best_element_val:
            best_element = element
            best_element_val = char_stats[element]
    return best_element

def get_equiped_weapon(char_stats):
    weapon = None
    for item in char_stats['items']:
        if item.slot == 'weapon':
            weapon = item
            break
    return weapon

def calculate_damage(base_damage, char_stats, critical_hit, is_spell):
    damage_instances = []
    for dam in base_damage:
        if dam.element in ('pushes', 'steals', 'attracts', 'advances', 'steals_mp', 'removes_ap'): #non-elemental hit types
            continue
        if dam.element == 'best' or dam.element == 'damage' or dam.element == 'best-element': #best/damage/best-element = damage in best element
            dam.element = get_best_element(char_stats)
            dam.element = ATTRIBUTE_TO_ELEMENT[dam.element]
        element_val = max(char_stats[DAMAGE_TYPE_TO_MAIN_STAT[dam.element]], 0)
        if not dam.heals:
            element_val = element_val + max(char_stats['pow'], 0)
            element_dam = char_stats[dam.element.lower() + "dam"]
            element_dam = element_dam + char_stats['dam']
            if critical_hit:
                element_dam += char_stats['cridam']
        else:
            element_dam = char_stats['heals']
        minimum_damage = (max(int((1 + element_val / 100.0) * dam.min_dam)
                                               + element_dam, 0))
        maximum_damage = (max(int((1 + element_val / 100.0) * dam.max_dam)
                                               + element_dam, 0))
        if is_spell:
            minimum_damage = minimum_damage * (100 + char_stats['perspedam'])/100
            maximum_damage = maximum_damage * (100 + char_stats['perspedam'])/100
        else:
            minimum_damage = minimum_damage * (100 + char_stats['perweadam'])/100
            maximum_damage = maximum_damage * (100 + char_stats['perweadam'])/100
        damage = CalculatedDamage(min_dam=minimum_damage,
                                  max_dam=maximum_damage,
                                  element=dam.element,
                                  steals=dam.steals,
                                  heals=dam.heals)
        
        damage_instances.append(damage)
    return damage_instances

