def get_best_element(char_stats):
    best_element = 'str'
    best_element_val = char_stats['str']
    for element in ['int', 'cha', 'agi']:
        if char_stats[element] > best_element_val:
            best_element = element
            best_element_val = char_stats[element]
    return best_element

